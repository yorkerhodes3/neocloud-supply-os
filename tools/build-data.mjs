#!/usr/bin/env node
// Extracts every markdown table in CONCEPT-IDEA.md into docs/assets/js/data/concept.js,
// keyed by the nearest heading, so the website renders the reviewed document's own
// content rather than a paraphrase that can drift. Run: npm run build:data
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'CONCEPT-IDEA.md'), 'utf8').split('\n');

const clean = (s) => s.trim()
  .replace(/\*\*(.+?)\*\*/g, '$1')
  .replace(/`([^`]+)`/g, '$1')
  .replace(/\\\|/g, '|');

const splitRow = (line) => {
  const cells = [];
  let cur = '', tick = false;
  const body = line.trim().replace(/^\|/, '').replace(/\|$/, '');
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c === '`') tick = !tick;
    if (c === '|' && !tick && body[i - 1] !== '\\') { cells.push(cur); cur = ''; continue; }
    cur += c;
  }
  cells.push(cur);
  return cells.map(clean);
};

const tables = {};
let heading = 'root';
for (let i = 0; i < src.length; i++) {
  const h = /^(#{2,3})\s+(.*)$/.exec(src[i]);
  if (h) { heading = h[2].trim(); continue; }
  if (/^\|/.test(src[i]) && /^\|\s*-{3}/.test(src[i + 1] || '')) {
    const head = splitRow(src[i]);
    const rows = [];
    let j = i + 2;
    while (j < src.length && /^\|/.test(src[j])) { rows.push(splitRow(src[j])); j++; }
    const key = tables[heading] ? `${heading} (${Object.keys(tables).filter(k => k.startsWith(heading)).length + 1})` : heading;
    tables[key] = { head, rows };
    i = j - 1;
  }
}

const pick = (prefix) => {
  const k = Object.keys(tables).find(t => t.startsWith(prefix));
  if (!k) throw new Error(`No table under heading starting "${prefix}"`);
  return tables[k];
};

// Capability map: A1–A10.
const lanes = [];
for (const k of Object.keys(tables).filter(t => /^A\d+\./.test(t))) {
  const [code, rest] = k.split('. ');
  const name = rest.split(':')[0].trim();
  lanes.push({ code, name, title: rest, functions: tables[k].rows.map(r => ({
    n: Number(r[0]), fn: r[1], desk: r[2], human: r[3], autonomy: r[4], replaces: r[5],
  })) });
}

const desks = pick('B2.').rows.map(r => ({
  name: r[0], functions: r[1].split(',').map(s => Number(s.trim())).filter(Boolean),
  tools: r[2], mandate: r[3], start: r[4],
}));

const data = {
  generatedFrom: 'CONCEPT-IDEA.md',
  pains: pick('What the pain costs').rows.map(r => ({ pain: r[0], looks: r[1], costs: r[2] })),
  audiences: pick('3. Who it is for').rows.map(r => ({ who: r[0], cares: r[1], meets: r[2] })),
  metrics: pick('5. What success looks like').rows.map(r => ({ signal: r[0], measure: r[1], target: r[2], when: r[3] })),
  lanes,
  desks,
  riskTools: pick('D2.'), signals: pick('D3.'), sources: pick('D4.'),
  tiers: pick('E2.'), messages: pick('E3.'),
  team: pick('H2.').rows.map(r => ({ role: r[0], count: r[1], owns: r[2] })),
  exceptions: pick('H4.'),
  ladder: pick('I1.').rows.map(r => ({ level: r[0], name: r[1], may: r[2], promote: r[3] })),
  evals: pick('I7.'),
  legacy: pick('Appendix J').rows.map(r => ({ category: r[0], by: r[1], external: r[2] })),
  scenarios: pick('Appendix K').rows.map(r => ({ n: Number(r[0]), name: r[1], signals: r[2], auto: r[3], human: r[4] })),
  roadmap: pick('Appendix L').rows.map(r => ({ phase: r[0], scope: r[1], autonomy: r[2], demo: r[3] })),
};

const out = `// GENERATED by tools/build-data.mjs from CONCEPT-IDEA.md — do not edit by hand.\n` +
  `export const CONCEPT = ${JSON.stringify(data, null, 1)};\n`;
writeFileSync(join(root, 'docs/assets/js/data/concept.js'), out);
console.log(`concept.js: ${lanes.reduce((a, l) => a + l.functions.length, 0)} functions, ${desks.length} desks, ` +
  `${data.scenarios.length} scenarios, ${data.roadmap.length} phases, ${data.legacy.length} legacy rows`);
